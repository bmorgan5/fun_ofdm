/*! \file viterbi.h
 *  \brief The convolutional code: an encoder, and a Viterbi decoder for it.
 *
 *  This is the forward error correction (802.11a-1999 section 17.3.5.5).
 *
 *  **Encoding.** The encoder keeps the last 7 data bits in a shift register.
 *  For each new bit it outputs two coded bits, A and B, each the parity of a
 *  fixed set of the register's bits (the generator polynomials). That doubles
 *  the bit count, so the code is rate 1/2, and spreads each data bit over 14
 *  coded bits. The redundancy is what lets the decoder fix errors.
 *
 *  ~~~
 *                  ┌──────────────────────┐  parity of taps g0 ──► A
 *  data bit ──────►│ 7-bit shift register │
 *                  └──────────────────────┘  parity of taps g1 ──► B
 *
 *  coded bits: A0 B0 A1 B1 A2 B2 ...  (one per byte, each 0 or 1)
 *  ~~~
 *
 *  Six zero tail bits after the data return the register to all zeros, so the
 *  decoder knows the state it ends in.
 *
 *  **Decoding.** The register has 64 possible states (the 6 older bits). For
 *  each state, the Viterbi algorithm keeps only the most likely sequence of
 *  data bits that ends in it, scored by how far that sequence's coded bits are
 *  from what was received. After the last bit it follows the best sequence
 *  back from state 0. That finds the most likely data without trying every
 *  sequence.
 *
 *  The decoder takes soft bits: 0 is a confident 0, 255 a confident 1, and
 *  127 means no idea (see puncturer.h). A barely-wrong bit costs a sequence
 *  less than a confidently-wrong one, which corrects far more errors than
 *  deciding each bit first. The decoder is SSE code generated by SPIRAL, and
 *  decodes two bits per step, so the data bit count must be even.
 *
 *  Unlike 802.11a, the generator polynomials are time-reversed and the A and
 *  B outputs are swapped.
 */

#ifndef VITERBI_H
#define VITERBI_H

#pragma once

#include <emmintrin.h>
#include <math.h>
#include <memory.h>
#include <mmintrin.h>
#include <pmmintrin.h>
#include <stdlib.h>
#include <xmmintrin.h>

#include <cstddef>
#include <cstdint>
#include <vector>

#define K 7
#define RATE 2
#define POLYS {121, 91}
#define NUMSTATES 64
#define DECISIONTYPE std::uint8_t
#define DECISIONTYPE_BITSIZE 8
#define COMPUTETYPE std::uint8_t

namespace fun {
// decision_t is a BIT vector

/*! \brief decision_t is a BIT vector */
typedef union {
  DECISIONTYPE t[NUMSTATES / DECISIONTYPE_BITSIZE];
  unsigned int w[NUMSTATES / 32];
  unsigned short s[NUMSTATES / 16];
  std::uint8_t c[NUMSTATES / 8];
} decision_t __attribute__((aligned(16)));

/*! \brief the metric_t attribute */
typedef union {
  COMPUTETYPE t[NUMSTATES];
} metric_t __attribute__((aligned(16)));

/*!
 * \brief The v struct
 *
 *  This struct is used as a helper to keep track of parameters during decoding.
 */
struct v {
  __attribute__((aligned(16))) metric_t metrics1; /* path metric buffer 1 */
  __attribute__((aligned(16))) metric_t metrics2; /* path metric buffer 2 */
  metric_t *old_metrics,
      *new_metrics;      /* Pointers to path metrics, swapped on every bit */
  decision_t* decisions; /* decisions */
  void (*update_blk)(struct v* vp, const COMPUTETYPE* syms, int nbits);
};

/*!
 * \brief The viterbi class
 */
class viterbi {
 private:
  COMPUTETYPE Branchtab[NUMSTATES / 2 * RATE] __attribute__((aligned(16)));

  void viterbi_chainback(struct v* vp,
                         std::uint8_t* data, /* Decoded output data */
                         std::size_t nbits,  /* Number of data bits */
                         unsigned int endstate);

  void FULL_SPIRAL(int nbits, std::uint8_t* Y, std::uint8_t* X,
                   const std::uint8_t* syms, std::uint8_t* dec,
                   std::uint8_t* Branchtab);

  /*!
   * \brief Create a new instance of a Viterbi decoder
   * \param len = FRAMEBITS (unpadded! data bits)
   */
  struct v* viterbi_alloc(int len);

  /*!
   * \brief Destroy instance of a Viterbi decoder
   * \param vp pointer to the v struct to free
   */
  void viterbi_free(struct v* vp);

  /*!
   * \brief Initialize decoder for start of new frame
   * \param vp pointer to v struct to initialize for decoding.
   * \param starting_state Initial state for viterbi decoder
   */
  void viterbi_init(struct v* vp, int starting_state);

  /*!
   * \brief Decode one frame worth of data.
   * \param vp Pointer to v struct used to store parameters and help with
   * decoding
   * \param symbols Input symbol to be decoded
   * \param data Output data that has been decoded
   *
   * NOTE: nbits has to match what was passed to viterbi_alloc(...)
   * FIXME: store nbits in struct v?
   */
  void viterbi_decode(struct v* vp, const COMPUTETYPE* symbols,
                      std::uint8_t* data, int nbits);

  /*! \brief set the viterbi decoder to use a specific implementation */
  void viterbi_update_blk_SPIRAL(struct v* vp, const COMPUTETYPE* syms,
                                 int nbits);
  // void viterbi_spiral(struct v *vp);

 public:
  /*!
   * \brief Decodes convolutionally encoded data using the viterbi algorithm.
   * \param symbols Coded symbols that need to be decoded.
   * \param data Output data that has been decoded.
   * \param data_bits Number of data bits that that should be left after
   * decoding. It must be even, since the decoder handles two bits at a time.
   */
  void conv_decode(std::uint8_t* symbols, std::uint8_t* data,
                   std::size_t data_bits);

  /*!
   * \brief Convolutionally encodeds data.
   * \param data The data to be coded.
   * \param symbols The coded output symbols.
   * \param data_bits The number of bits in the data input.
   */
  void conv_encode(std::uint8_t* data, std::uint8_t* symbols,
                   std::size_t data_bits);
};

}  // namespace fun

#endif  // VITERBI_H
